"""Write Hermes' config for BolDoc from the secret files (run on the box before `docker compose up hermes`).

Hermes (docs/design/hermes.md) writes long documents through control's tools and calls the writer's model through
control's metering proxy; it sees no other tool, no internet and no Bedrock key. Usage:
    python3 infra/hermes/render_config.py ~/app/secrets
reads <secrets>/hermes_api_key and <secrets>/hermes_mcp_key (made once with `--new-keys`), writes
<secrets>/hermes/config.yaml and <secrets>/hermes/hermes.env. Keys are never printed.
"""
import secrets
import sys
from pathlib import Path

CONFIG = """# BolDoc's long-document writer (generated by infra/hermes/render_config.py; do not edit by hand)
model:
  provider: boldoc
  default: writer
providers:
  boldoc:
    api: http://control:8091/internal/llm/v1      # control's metering proxy: the writer's model, its key, a cap
    api_key: {mcp_key}
    transport: openai_chat
    discover_models: false
    models:
      writer:
        context_length: 131072
platform_toolsets:
  api_server: ["mcp-boldoc"]
tools:
  tool_search:
    enabled: "off"                               # our eight tools stay in view (tool search cost 4 calls a run)
agent:
  max_turns: 100                                 # research adds up to 40 tool calls
  disabled_toolsets: [clarify, browser, code_execution, computer_use, connections, cronjob, delegation, file,
                      image_gen, video_gen, kanban, memory, session_search, skills, terminal, todo, tts, vision,
                      video, web, search, safe, x_search, catalog, desktop_ui, project, context_engine]
memory:
  memory_enabled: false
  user_profile_enabled: false
skills:
  auto_load: []
plugins:
  auto_update_check_hours: 0
security:
  allow_lazy_installs: false
telemetry:
  shared_metrics:
    enabled: false
    send: false
mcp_servers:
  boldoc:
    url: http://control:8091/internal/mcp
    headers:
      Authorization: "Bearer {mcp_key}"
    timeout: 1800                                # ask_caller waits for the caller's answers
    connect_timeout: 20
    trust: full
    tools:
      include: [get_brief, write_section, ask_caller, check, finish, get_material, web_search, read_page]
      prompts: false
      resources: false
"""


def main() -> None:
    root = Path(sys.argv[1]).expanduser()
    if "--new-keys" in sys.argv:
        for name in ("hermes_api_key", "hermes_mcp_key"):
            p = root / name
            if p.exists():
                sys.exit(f"{p} exists: refusing to overwrite a key")
            p.write_text(secrets.token_urlsafe(32))
            p.chmod(0o600)
    api_key = (root / "hermes_api_key").read_text().strip()
    mcp_key = (root / "hermes_mcp_key").read_text().strip()
    out = root / "hermes"
    out.mkdir(mode=0o755, exist_ok=True)
    (out / "config.yaml").write_text(CONFIG.format(mcp_key=mcp_key))
    (out / "hermes.env").write_text(f"API_SERVER_ENABLED=true\nAPI_SERVER_HOST=0.0.0.0\nAPI_SERVER_KEY={api_key}\n")
    (out / "config.yaml").chmod(0o644)   # read by the container's user (uid 10000) through a read-only mount
    (out / "hermes.env").chmod(0o644)    # read by the container's user through a read-only mount
    print(f"wrote {out}/config.yaml and {out}/hermes.env")


if __name__ == "__main__":
    main()
